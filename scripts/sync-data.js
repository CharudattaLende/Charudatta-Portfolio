/**
 * Synchronization Script for Portfolio Data
 * Reads canonical portfolio-data.json and updates portfolio-data.js
 * Run with: node scripts/sync-data.js
 */

const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const jsonPath = path.join(rootDir, 'portfolio-data.json');
const jsPath = path.join(rootDir, 'portfolio-data.js');

try {
  console.log('Reading canonical portfolio-data.json...');
  const rawData = fs.readFileSync(jsonPath, 'utf8');
  const parsedData = JSON.parse(rawData);

  // Validate required structure
  if (!parsedData.profile || !parsedData.projectsGrid || !parsedData.contact) {
    throw new Error('portfolio-data.json is missing required sections (profile, projectsGrid, contact).');
  }

  // Ensure resumeUrl is preserved as empty string if not provided
  if (typeof parsedData.profile.resumeUrl !== 'string') {
    parsedData.profile.resumeUrl = '';
  }

  const generatedJs = `/**
 * PORTFOLIO DATA CONFIGURATION
 * Generated automatically from canonical single source of truth: portfolio-data.json
 * Do NOT edit this file manually. Edit portfolio-data.json and run 'npm run sync-data'.
 */

(function () {
  const EMBEDDED_DATA = ${JSON.stringify(parsedData, null, 2)};

  // Expose initial data immediately for synchronous consumers
  if (typeof window !== 'undefined') {
    window.PORTFOLIO_DATA = EMBEDDED_DATA;
  }
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = EMBEDDED_DATA;
  }

  // If in browser environment with fetch available, refresh dynamically from canonical JSON
  if (typeof window !== 'undefined' && typeof window.fetch === 'function') {
    const jsonUrl = './portfolio-data.json?v=' + Date.now();
    fetch(jsonUrl)
      .then((res) => {
        if (!res.ok) throw new Error('HTTP ' + res.status);
        return res.json();
      })
      .then((remoteData) => {
        window.PORTFOLIO_DATA = remoteData;
        window.dispatchEvent(new CustomEvent('portfolioDataLoaded', { detail: remoteData }));
      })
      .catch((err) => {
        // Fall back gracefully to EMBEDDED_DATA
        console.debug('Using embedded portfolio-data snapshot (fetch bypassed):', err.message);
      });
  }
})();
`;

  fs.writeFileSync(jsPath, generatedJs, 'utf8');
  console.log('Successfully synchronized portfolio-data.json -> portfolio-data.js');
} catch (err) {
  console.error('Data synchronization failed:', err.message);
  process.exit(1);
}
