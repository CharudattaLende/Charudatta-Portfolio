def test_external_model_inference_contract(monkeypatch):
    """
    Tests the client contract with the Colab /generate inference API.
    Request: {"prompt": "...", "max_tokens": ...}
    Response: {"text": "...", "tokens_generated": 50, "latency_ms": 120.0, "tokens_per_sec": 41.6, "finish_reason": "length"}
    Verifies model_status is 'pending' initially and becomes 'connected' ONLY after successful inference.
    """
    recorded_calls = []

    class MockResponse:
        status_code = 200
        def json(self):
            return {
                "text": "VerbiTech answer generated by step 2000 checkpoint.",
                "tokens_generated": 50,
                "latency_ms": 115.4,
                "tokens_per_sec": 43.3,
                "finish_reason": "length"
            }

    class MockClient:
        def __init__(self, *args, **kwargs):
            pass
        def __enter__(self):
            return self
        def __exit__(self, *args):
            pass
        def post(self, url, json=None, **kwargs):
            recorded_calls.append((url, json))
            return MockResponse()

    import httpx
    monkeypatch.setattr(httpx, "Client", MockClient)
    
    # Reset connection status
    inference_engine._is_connected = False
    assert inference_engine.get_model_status() == "pending"

    original_url = inference_engine.endpoint_url
    try:
        # User provides base ngrok URL: helper should normalize to /generate
        inference_engine.endpoint_url = "https://mock-colab-verbitech.ngrok-free.app"
        response = client.post("/api/chat", json={"message": "Deep architecture analysis of data pipelines"})
        assert response.status_code == 200
        data = response.json()

        # Contract verification
        assert len(recorded_calls) == 1
        call_url, call_payload = recorded_calls[0]
        assert call_url == "https://mock-colab-verbitech.ngrok-free.app/generate"
        assert "prompt" in call_payload
        assert "max_tokens" in call_payload

        # Verified real text generation
        assert data["model_status"] == "connected"
        assert data["generation_source"] == "verbitech_model"
        assert "step 2000 checkpoint" in data["reply"]
        assert inference_engine.get_model_status() == "connected"
    finally:
        inference_engine.endpoint_url = original_url
        inference_engine._is_connected = False


def test_external_model_inference_failure_reverts_to_pending(monkeypatch):
    """
    Verifies that if an external model call fails (e.g. Colab offline),
    model_status safely reports 'pending' and serves grounded facts without crashing.
    """
    class MockFailingClient:
        def __init__(self, *args, **kwargs):
            pass
        def __enter__(self):
            return self
        def __exit__(self, *args):
            pass
        def post(self, url, json=None, **kwargs):
            raise httpx.ConnectError("Colab endpoint unreachable")

    import httpx
    monkeypatch.setattr(httpx, "Client", MockFailingClient)

    inference_engine._is_connected = False
    original_url = inference_engine.endpoint_url
    try:
        inference_engine.endpoint_url = "https://failing-colab-endpoint.ngrok-free.app"
        response = client.post("/api/chat", json={"message": "Explain your engineering background"})
        assert response.status_code == 200
        data = response.json()
        assert data["model_status"] == "pending"
        assert data["generation_source"] == "grounded_knowledge_fallback"
        assert "Charudatta" in data["reply"]
    finally:
        inference_engine.endpoint_url = original_url
        inference_engine._is_connected = False


